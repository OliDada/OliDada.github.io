# Builds ../data.js for Time Capsule from Wikipedia's daily most-read lists (English Wikipedia, all devices).
# Resumable and parallel: each day's list is cached in raw/. Run: python3 capsule.py   (or --build to only rebuild data.js)
import json, os, re, sys, time, random, datetime, urllib.request, urllib.error
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
UA = "OliD.is Time Capsule daily game builder (https://olid.is)"
here = os.path.dirname(os.path.abspath(__file__)); RAW = os.path.join(here, "raw"); os.makedirs(RAW, exist_ok=True)
FIRST, LAST, STEP = datetime.date(2016, 1, 1), datetime.date(2026, 10, 31), 3      # every 3rd day
days = [FIRST + datetime.timedelta(i) for i in range(0, (LAST - FIRST).days + 1, STEP)]
def fetch(d):
    fn = os.path.join(RAW, f"{d}.json")
    if os.path.exists(fn) and os.path.getsize(fn) > 0: return
    url = f"https://wikimedia.org/api/rest_v1/metrics/pageviews/top/en.wikipedia/all-access/{d:%Y/%m/%d}"
    for k in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30) as r:
                arts = json.loads(r.read())["items"][0]["articles"]
            data = json.dumps([[a["article"], a["views"]] for a in arts[:300]]); open(fn, "w").write(data); return
        except urllib.error.HTTPError as e:
            if e.code == 404: open(fn, "w").write("[]"); return      # Wikimedia has no list for a few days
            time.sleep(2 * (k + 1))
        except Exception: time.sleep(2 * (k + 1))
    print("FAIL", d, flush=True)
if "--build" not in sys.argv:
    with ThreadPoolExecutor(5) as ex: list(ex.map(fetch, days))
have = {d: json.load(open(os.path.join(RAW, f"{d}.json"))) for d in days if os.path.exists(os.path.join(RAW, f"{d}.json")) and os.path.getsize(os.path.join(RAW, f"{d}.json")) > 0}
# Pages that are popular on lots of days (Google, YouTube, "Deaths in 2024"...) say nothing about the day: drop them.
seen = Counter(t for lst in have.values() for t, _ in lst[:300])
EVERGREEN = {t for t, n in seen.items() if n > len(have) * .04}
SKIP = re.compile(r"^(Main_Page|Special:|Wikipedia:|File:|Portal:|Help:|Template:|Category:|User:|Talk:|-$|Undefined|XXX)|porn|sex|nude|xxx|onlyfans|hentai|erotic|deaths_in|list_of_.*deaths", re.I)
def clean(t):
    t = t.replace("_", " ")
    return re.sub(r"\b(20[12]\d|199\d)\b", "____", t)        # years in titles would give it away
out = []
for d, lst in sorted(have.items()):
    pick = []
    for t, v in lst:
        if t in EVERGREEN or SKIP.search(t): continue
        c = clean(t)
        if c not in [clean(p) for p in pick]: pick.append(t.replace("_", " "))
        if len(pick) == 8: break
    if len(pick) == 8: out.append([d.isoformat(), pick])
open(os.path.join(here, "..", "data.js"), "w", encoding="utf-8").write(
    "// Generated by tools/capsule.py from Wikipedia's daily most-read lists (English Wikipedia).\n"
    "// Each entry: [date, the 8 most-read pages that day, leaving out pages that are popular all the time]. The game hides years in titles.\n"
    f"window.CAPSULE_DAYS = {json.dumps(out, separators=(',', ':'), ensure_ascii=False)};\n")
print("days", len(out), "of", len(days), "evergreen", len(EVERGREEN))
for d, p in random.Random(4).sample(out, min(4, len(out))): print(d, " | ".join(p))
