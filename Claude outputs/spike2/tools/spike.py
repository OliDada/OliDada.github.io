# Builds ../data.js for Spike: weekly English Wikipedia views (people, not bots) for each page, July 2015 to last week.
# Resumable and parallel: raw daily counts are cached in raw2/ (delete it to refresh with newer weeks). Run: python3 spike.py   (or --build to only rebuild data.js)
import json, os, sys, time, base64, urllib.request, urllib.parse, datetime
from concurrent.futures import ThreadPoolExecutor
UA = "OliD.is Spike daily game builder (https://olid.is)"
# Per-article counts start on 1 July 2015 (first Monday: 6 July). End on the last full week before today.
START = datetime.date(2015, 7, 6)
END = datetime.date.today() - datetime.timedelta(days=datetime.date.today().weekday() + 1)   # last Sunday
here = os.path.dirname(os.path.abspath(__file__))
rows = [[s.strip() for s in l.split("|")] for l in open(os.path.join(here, "articles.txt"), encoding="utf-8") if l.strip() and not l.startswith("#")]
os.makedirs(os.path.join(here, "raw2"), exist_ok=True)
days = [START + datetime.timedelta(i) for i in range((END - START).days + 1)]
rawfile = lambda t: os.path.join(here, "raw2", t.replace("/", "_") + ".json")
def fetch(title):
    if os.path.exists(rawfile(title)): return
    url = f"https://wikimedia.org/api/rest_v1/metrics/pageviews/per-article/en.wikipedia/all-access/user/{urllib.parse.quote(title.replace(' ', '_'), safe='')}/daily/{START:%Y%m%d}/{END:%Y%m%d}"
    for k in range(5):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30) as r:
                by = {it["timestamp"][:8]: it["views"] for it in json.loads(r.read())["items"]}
            json.dump([by.get(d.strftime("%Y%m%d"), 0) for d in days], open(rawfile(title), "w")); print("ok", title, flush=True); return
        except urllib.error.HTTPError as e:
            if e.code == 404: print("404", title, flush=True); return
            time.sleep(2 * (k + 1))
        except Exception: time.sleep(2 * (k + 1))
    print("FAIL", title, flush=True)
if "--build" not in sys.argv:
    with ThreadPoolExecutor(6) as ex: list(ex.map(lambda r: fetch(r[0]), rows))
out, rep = [], []
for title, name, cat, *aka in rows:
    if not os.path.exists(rawfile(title)): rep.append("   MISSING " + title); continue
    d = json.load(open(rawfile(title))); w = [sum(d[i:i + 7]) for i in range(0, len(d), 7)]
    mx = max(w)
    if mx == 0: rep.append("   EMPTY " + title); continue
    peak = w.index(mx); total = sum(w)
    b = base64.b64encode(bytes(round(x / mx * 255) for x in w)).decode()
    out.append([title, name, cat, [a.lower() for a in aka], b, peak, mx, total])
    rep.append(f"{total:11d} {mx:9d} {START + datetime.timedelta(peak * 7):%Y-%m}  {name}")
open(os.path.join(here, "..", "data.js"), "w", encoding="utf-8").write(
    f"// Generated by tools/spike.py: weekly English Wikipedia views, {START:%d %b %Y} to {END:%d %b %Y}.\n"
    f"window.SPIKE_START = '{START.isoformat()}';\nwindow.SPIKE_DATA = {json.dumps(out, separators=(',', ':'), ensure_ascii=False)};\n")
print("total      peakweek  peak     name\n" + "\n".join(sorted(rep)))
print("ENTRIES", len(out), "of", len(rows))
