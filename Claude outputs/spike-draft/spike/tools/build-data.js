// Builds ../data.js for Spike from Wikipedia's public pageview API.
// Run:  node build-data.js            (needs wikimedia.org reachable)
//       node build-data.js --fake     (made-up graphs, only for testing the game's look; never ship these)
// Each entry: [title, name, category, [other names], base64 daily views (0-255 scaled), peak day of year, peak views, total views]
const fs = require('fs'), path = require('path');
const YEAR = 2025, FAKE = process.argv.includes('--fake');
const rows = fs.readFileSync(path.join(__dirname, 'articles.txt'), 'utf8').split('\n').filter(l => l.trim() && !l.startsWith('#')).map(l => l.split('|').map(s => s.trim()));
const days = Array.from({ length: 365 }, (_, i) => new Date(Date.UTC(YEAR, 0, 1 + i)));
const ymd = d => d.toISOString().slice(0, 10).replace(/-/g, '');
async function views(title) {
  if (FAKE) { // a smooth seasonal hump plus one spike, at a place picked from the title
    let h = 0; for (const c of title) h = (h * 31 + c.charCodeAt(0)) >>> 0;
    const peak = h % 365, w = 2 + h % 9;
    return days.map((_, i) => Math.round(2000 + 800 * Math.sin((i + h) / 58) + 60000 * Math.exp(-((i - peak) ** 2) / (2 * w * w)) + Math.random() * 400 + (i % 7 === 6 ? 300 : 0)));
  }
  const url = `https://wikimedia.org/api/rest_v1/metrics/pageviews/per-article/en.wikipedia/all-access/user/${encodeURIComponent(title.replace(/ /g, '_'))}/daily/${ymd(days[0])}/${ymd(days[364])}`;
  const res = await fetch(url, { headers: { 'User-Agent': 'OliD.is Spike daily game builder (https://olid.is)' } });
  if (!res.ok) throw new Error(res.status + ' ' + title);
  const j = await res.json(), by = {}; for (const it of j.items) by[it.timestamp.slice(0, 8)] = it.views;
  return days.map(d => by[ymd(d)] || 0);
}
(async () => {
  const out = [], report = [];
  for (const [title, name, cat, ...aka] of rows) {
    try {
      const v = await views(title), max = Math.max(...v), peak = v.indexOf(max), total = v.reduce((a, b) => a + b, 0);
      const sorted = v.slice().sort((a, b) => a - b), median = sorted[182] || 1;
      const bytes = Buffer.from(v.map(x => Math.round(x / max * 255)));
      out.push([title, name, cat, aka.map(s => s.toLowerCase()), bytes.toString('base64'), peak, max, total]);
      report.push(`${(max / median).toFixed(1).padStart(7)}x  ${String(total).padStart(9)}  ${name}`);
      if (!FAKE) await new Promise(r => setTimeout(r, 120));
    } catch (e) { report.push('   FAIL  ' + e.message); }
  }
  fs.writeFileSync(path.join(__dirname, '..', 'data.js'), `// Generated by tools/build-data.js from Wikipedia pageviews (${YEAR}).${FAKE ? ' FAKE TEST DATA, DO NOT SHIP.' : ''}\nwindow.SPIKE_YEAR = ${YEAR};\nwindow.SPIKE_DATA = ${JSON.stringify(out)};\n`);
  console.log('peak/median  total  name\n' + report.sort().reverse().join('\n'));
})();
