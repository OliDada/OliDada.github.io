# Resumable, parallel version of tools/build-data.js: fetches daily views per article, caches raw, then writes ../data.js
import json, os, sys, time, base64, urllib.request, urllib.parse, datetime
from concurrent.futures import ThreadPoolExecutor
UA = "OliD.is Spike daily game builder (https://olid.is)"
YEAR = 2025
here = os.path.dirname(os.path.abspath(__file__))
rows = [[s.strip() for s in l.split("|")] for l in open(os.path.join(here, "articles.txt")) if l.strip() and not l.startswith("#")]
os.makedirs(os.path.join(here, "raw"), exist_ok=True)
days = [datetime.date(YEAR, 1, 1) + datetime.timedelta(i) for i in range(365)]
def fetch(title):
    fn = os.path.join(here, "raw", title.replace("/", "_") + ".json")
    if os.path.exists(fn): return
    url = f"https://wikimedia.org/api/rest_v1/metrics/pageviews/per-article/en.wikipedia/all-access/user/{urllib.parse.quote(title.replace(' ', '_'), safe='')}/daily/{YEAR}0101/{YEAR}1231"
    for k in range(6):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30) as r:
                j = json.loads(r.read()); by = {it["timestamp"][:8]: it["views"] for it in j["items"]}
                json.dump([by.get(d.strftime("%Y%m%d"), 0) for d in days], open(fn, "w")); print("ok", title, flush=True); return
        except urllib.error.HTTPError as e:
            if e.code == 404: print("404", title, flush=True); return
            time.sleep(2 * (k + 1))
        except Exception: time.sleep(2 * (k + 1))
    print("FAIL", title, flush=True)
if "--build" not in sys.argv:
    with ThreadPoolExecutor(6) as ex: list(ex.map(lambda r: fetch(r[0]), rows))
out, rep = [], []
for title, name, cat, *aka in rows:
    fn = os.path.join(here, "raw", title.replace("/", "_") + ".json")
    if not os.path.exists(fn): rep.append("   MISSING " + title); continue
    v = json.load(open(fn)); mx = max(v)
    if mx == 0: rep.append("   EMPTY " + title); continue
    peak = v.index(mx); total = sum(v); med = sorted(v)[182] or 1
    b = base64.b64encode(bytes(round(x / mx * 255) for x in v)).decode()
    out.append([title, name, cat, [a.lower() for a in aka], b, peak, mx, total])
    rep.append(f"{mx/med:7.1f}x {total:10d}  {name}")
open(os.path.join(here, "..", "data.js"), "w").write(f"// Generated by tools/build-data.js from Wikipedia pageviews ({YEAR}).\nwindow.SPIKE_YEAR = {YEAR};\nwindow.SPIKE_DATA = {json.dumps(out, separators=(',', ':'), ensure_ascii=False)};\n")
print("peak/median  total  name\n" + "\n".join(sorted(rep, reverse=True)))
print("ENTRIES", len(out), "of", len(rows))
